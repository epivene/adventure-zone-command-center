type Database = typeof database;

export async function ensureCommercialOfferSeed(database: Database): Promise<void> {
  await ensureBusinessSourceSeed(database);
  const source = (
    await database
      .select({ id: businessSourceDocuments.id })
      .from(businessSourceDocuments)
      .where(
        eq(
          businessSourceDocuments.originalFilename,
          "ADVENTURE ZONE STICKY NOTES.docx.pdf",
        ),
      )
      .limit(1)
  )[0];

  const repository = new CommercialOfferRepository(database);
  await repository.seedMissing(
    COMMERCIAL_OFFER_SEEDS.map((offer) => ({
      ...offer,
      sourceDocumentId: source?.id ?? null,
    })),
  );
}
